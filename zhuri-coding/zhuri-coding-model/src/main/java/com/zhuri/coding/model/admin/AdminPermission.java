package com.zhuri.coding.model.admin;

/**
 * 运营后台权限点。
 *
 * <p><b>为什么是枚举而不是权限表</b>：权限点与接口一一对应，属于代码契约。
 * 一旦入库，就会出现"代码加了新接口、库里没加对应权限点"的漂移——这种漂移的结果是
 * 新接口谁都没权限调，而问题要到上线才暴露。写在代码里则接口与权限点同时进版本。
 *
 * <p><b>命名规范</b>：{@code 资源_动作}，资源用单数。新增权限点时必须同时挂到
 * {@link AdminRole} 的某个角色上，否则它永远不生效。
 */
public enum AdminPermission {

    /** 查看举报队列（列表、详情） */
    REPORT_VIEW("查看举报"),

    /** 处置举报（驳回/警告/下架/折叠，并回执举报人） */
    REPORT_HANDLE("处置举报"),

    /** 折叠内容（温和处置：不删除，降权+标注） */
    CONTENT_FOLD("折叠内容"),

    /** 下架内容（重处置：线上不可见，需同步清索引与向量） */
    CONTENT_TAKE_DOWN("下架内容"),

    /** 终审内容申诉（allow 可解除折叠/撤销 AIGC 标注） */
    APPEAL_REVIEW("终审申诉"),

    /**
     * 复核 AI 审核队列（对已 flagged 的内容做人工放行/确认）。
     *
     * <p>与 {@link #APPEAL_REVIEW} 分开，是因为两者的<b>触发方向相反</b>：申诉是
     * 「作者告状 → 运营裁决」，被动响应作者的质疑；复核是「运营主动巡检」，
     * 捞回那些<b>作者几乎感知不到</b>的静默降权（AIGC flagged 不删内容、不下架，
     * 只关打赏/禁售/不入向量库，作者往往不知道自己被打了标，也就无从申诉）。
     * 动作相似但来源不同，混成一个权限点后就没法把"巡检"单独下放或收权。
     */
    AUDIT_REVIEW("复核AI审核"),

    /** 配置运营位（话题、活动、Banner） */
    OPS_CONFIG("配置运营位"),

    /**
     * 管理活动（新建、编辑、上下线、删除草稿）。
     *
     * <p>与 {@link #OPS_CONFIG} 分开，因为两者改的是不同性质的东西：运营位配置改的是
     * <b>已有内容出现在哪里</b>（把哪个圈子摆到人气位、把哪个话题摆到推荐位），
     * 而活动是<b>凭空新建一条对外可见的内容</b> —— 标题、封面、时间窗、关联话题都要人来定。
     * 合成一个权限点，等于任何能调整人气位的人都能发布站级活动。
     */
    ACTIVITY_MANAGE("管理活动"),

    /** 审核小册（申报审核、上架审核、发布小节、下架） */
    BOOKLET_MANAGE("管理小册"),

    /** 审核沸点（通过、驳回、删除违规沸点） */
    PINS_MANAGE("管理沸点"),

    /** 警告用户 */
    USER_WARN("警告用户"),

    /** 封禁用户 */
    USER_BAN("封禁用户"),

    /** 授予/回收运营角色 */
    ROLE_GRANT("管理运营角色"),

    /**
     * 管理运营账号（新建、启用/停用）。
     *
     * <p>与 {@link #ROLE_GRANT} 分开，是因为两者危险程度不同：授予角色是"让已有的人多一份权力"，
     * 而新建账号是在扩充"谁可以进入这套系统"的名单。把两者合成一个权限点，等于任何能调整
     * 角色的人都能凭空造出一个超管账号，绕开"角色变更需要超管"这条约束。
     */
    ACCOUNT_MANAGE("管理运营账号");

    private final String desc;

    AdminPermission(String desc) {
        this.desc = desc;
    }

    public String getDesc() {
        return desc;
    }

    /** 枚举名即权限编码（与注解 {@code @RequireAdminPermission} 的值一致） */
    public String getCode() {
        return name();
    }
}
