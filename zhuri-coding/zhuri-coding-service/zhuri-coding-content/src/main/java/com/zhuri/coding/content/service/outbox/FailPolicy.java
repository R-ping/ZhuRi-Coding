package com.zhuri.coding.content.service.outbox;

/**
 * 重试耗尽后的终态策略。
 *
 * <p><b>为什么需要它</b>：最初 Outbox 只有一种终态——重试超限置 {@code DEAD} 等人工介入，
 * 这对资金类副作用是正确的（宁可报警也不能静默丢）。但另外几类业务的正确答案不是"等人工"：
 * <ul>
 *   <li><b>内容审核</b>：系统故障导致审核跑不完，不该把用户正常内容判为违规或一直不可见 ——
 *       应当"降级放行"（保持内容可见），失败方向的错比漏判更不可接受；</li>
 *   <li><b>可重建的派生数据</b>（ES 索引、缓存预热）：失败可以丢弃，另有全量重建手段兜底。</li>
 * </ul>
 * 把策略做成 Handler 的声明式属性，而不是散落在各自的补偿扫描器里，是为了让
 * 「失败时哪个方向更不可接受」这个判断**可被读到、可被统一调度**。
 *
 * @see OutboxHandler#failPolicy()
 */
public enum FailPolicy {

    /**
     * 重试耗尽 → 置 DEAD + ERROR 告警，等人工介入。
     * <p>适用：漏做不可接受的场景（资金、权限、通知送达）。
     */
    DEAD,

    /**
     * 重试耗尽 → 回调 {@link OutboxHandler#onExhausted(String, String)} 做业务降级，随后置 DONE。
     * <p>适用：错做不可接受的场景（内容审核误判、状态误改）——宁可放过，不要错杀。
     */
    DEGRADE,

    /**
     * 重试耗尽 → 直接置 DONE，不做任何补偿。
     * <p>适用：结果可重建的场景（ES 索引、缓存）。<b>使用前提是确实存在重建手段</b>，
     * 否则等价于静默丢数据。
     */
    DISCARD
}
