-- ap_coding_answer_record：加 status 列，把「今日题」的发放状态落到库里
-- （Coding 延展第一层 · 每日一题 / 库：leadnews_article）
--
-- 背景：原先抽题不写库，只在 Redis 里存一个 `coding:daily2:{userId}:{日期}` -> poolId，
--       用来回答两个问题：① 今天发给你的是哪道题（刷新页面要看到同一道）；
--       ② 提交时校验"你交的这道是不是今天发给你的那道"。
--       DB 流水则是「答完」才 insert 的，所以抽题阶段除了 Redis 什么都不留 ——
--       这也是每日一题对 Redis 产生依赖的原因。
--
-- 改法：抽题即落库（status = 0「已发放未作答」），作答时改成 1。
--       「今天发的是哪道」变成流水本身的一件事，Redis 在这个功能里被完全移除。
--
-- 为什么必须新增列、不能复用已有字段：
--       「已作答但模型没评出来」是靠 level IS NULL 表达的（本表没有 pending 列）。
--       如果拿 level IS NULL 兼表「未作答」，两种状态就分不开了 ——
--       计数、平均等级、今日是否已答全都会算错。
--
-- 执行方式（本项目约定：脚本入库，需手动执行）：
--   mysql -h127.0.0.1 -uroot -p123456 --default-character-set=utf8mb4 leadnews_article < add_coding_answer_record_status.sql
--   ⚠️ 必须带 --default-character-set=utf8mb4，否则中文注释会双重编码成乱码。
--
-- ⚠️ MySQL 不支持 ADD COLUMN IF NOT EXISTS，本脚本不可重复执行。
-- ⚠️ 执行期间应用应停写（本表的历史行全部是「已作答」，第 2 步依赖这一点来回填）。
-- =============================================================================

-- ---------------------------------------------------------------------------
-- 1. 加列
--    默认 0 取的是"生命周期起点"的语义：这条流水刚被创建时就是「已发放未作答」。
--    新链路的两处写入都显式带 status（抽题写 0、提交写 1），不依赖默认值。
-- ---------------------------------------------------------------------------
ALTER TABLE `ap_coding_answer_record`
  ADD COLUMN `status` TINYINT NOT NULL DEFAULT 0
      COMMENT '0=已发放未作答 1=已作答';

-- ---------------------------------------------------------------------------
-- 2. 回填历史行
--    加列之前，本表只有一条写入路径（作答落库），所以存量行全部是「已作答」。
--    不回填的话，历史作答会被当成"只发放过"，用户的连续天数、平均等级、活跃月份数会集体少算。
-- ---------------------------------------------------------------------------
UPDATE `ap_coding_answer_record` SET `status` = 1 WHERE `status` = 0;

